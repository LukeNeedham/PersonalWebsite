/**
 * BUILD TIME ONLY. Run by `yarn generate` (also as the pre-step of `dev` and `build`).
 *
 * Renders the markdown articles to HTML and compiles the article styling to CSS,
 * writing both to `src/generated`. The app (`src`) only ever imports these outputs;
 * it contains no markdown, highlighting or style-generation code.
 */
import fs from "node:fs/promises"
import path from "node:path"
import {renderMarkdown} from "./blog/renderMarkdown"
import {articleStyles} from "./blog/articleStyles"
import {chakraToCss} from "./blog/chakraToCss"

const root = path.join(__dirname, "..")
const contentDir = path.join(root, "content", "blog")
const outDir = path.join(root, "src", "generated")

async function main() {
    await fs.mkdir(outDir, {recursive: true})

    // Article id is the markdown file name
    const files = (await fs.readdir(contentDir)).filter(it => it.endsWith(".md")).sort()
    const html: Record<string, string> = {}
    for (const file of files) {
        const markdown = await fs.readFile(path.join(contentDir, file), "utf-8")
        html[path.basename(file, ".md")] = await renderMarkdown(markdown)
    }
    await fs.writeFile(path.join(outDir, "blog-html.json"), JSON.stringify(html, null, 2))

    const banner = "/* GENERATED by scripts/build-blog.ts from the Chakra theme. Do not edit. */\n\n"
    await fs.writeFile(path.join(outDir, "blog-article.css"), banner + chakraToCss(articleStyles))

    console.log(`Generated ${files.length} blog articles and article CSS in ${path.relative(root, outDir)}`)
}

main().catch(error => {
    console.error(error)
    process.exit(1)
})
